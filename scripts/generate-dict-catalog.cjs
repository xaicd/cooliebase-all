#!/usr/bin/env node
/**
 * 从**源头**（初始化 SQL 的 `system_dict_data`）生成字典目录。
 *
 * 为什么要有这一步：`status` 这类列允许哪些取值，本仓此前**无处声明** ——
 * 元数据里的注释是缩写（「开启状态」），契约里没有，校验器只当 `z.string()`。
 * 而源头其实一直有：`system_dict_data` 里有 210 个字典类型、1036 条 (label, value)。
 *
 * 于是：**字典是唯一真源，目录是它的生成物**（§25 单一真源）。
 * 元数据只声明 `dictType`（表↔字典的链接），**不复制取值** ——
 * 否则字典一改，复制出去的那份就漂了。
 *
 * 用法：
 *   node scripts/generate-dict-catalog.cjs            # 覆盖写 scripts/data/system-dict-catalog.ts
 *   node scripts/generate-dict-catalog.cjs --check    # 仅校验生成物与源一致（门禁用）
 */
const fs = require("fs")
const path = require("path")

const ROOT = path.resolve(__dirname, "..")
const SOURCE_SQL = "sql/init/cooliebase_all_next_v1.0.0_postgresql.sql"
const OUT = "scripts/data/system-dict-catalog.ts"

function readDict() {
  const abs = path.join(ROOT, SOURCE_SQL)
  if (!fs.existsSync(abs)) throw new Error(`源头缺失: ${SOURCE_SQL}`)
  const sql = fs.readFileSync(abs, "utf8")

  // ① 字典类型：('id', '标签', 'type_key', 'ACTIVE', remark, NOW(), NOW())
  const typeRows = sql.match(/\(\s*'(\d+)',\s*'([^']*)',\s*'([a-z_]+)',\s*'ACTIVE'/g) || []
  const types = {}
  for (const row of typeRows) {
    const m = row.match(/\(\s*'(\d+)',\s*'([^']*)',\s*'([a-z_]+)',\s*'ACTIVE'/)
    types[m[1]] = { key: m[3], label: m[2] }
  }

  // ② 字典数据：('id', 'dict_type_id', 'label', 'value', ...)
  const marker = 'INSERT INTO "system_dict_data"'
  if (!sql.includes(marker)) throw new Error(`源头缺少 ${marker}`)
  const seg = sql.split(marker)[1]
  const dataRows = seg.match(/\(\s*'(\d+)',\s*'(\d+)',\s*'([^']*)',\s*'([^']*)'/g) || []

  const catalog = {}
  for (const row of dataRows) {
    const m = row.match(/\(\s*'(\d+)',\s*'(\d+)',\s*'([^']*)',\s*'([^']*)'/)
    const type = types[m[2]]
    if (!type) continue
    catalog[type.key] = catalog[type.key] || { label: type.label, options: [] }
    catalog[type.key].options.push({ value: m[4], label: m[3] })
  }

  const withOptions = Object.keys(catalog).length
  if (withOptions === 0) throw new Error("源头解析出 0 个带取值的字典类型（解析可能已失效）")
  return catalog
}

function render(catalog) {
  const keys = Object.keys(catalog).sort()
  const body = keys
    .map((k) => {
      const { label, options } = catalog[k]
      const opts = options
        .map((o) => `      { value: ${JSON.stringify(o.value)}, label: ${JSON.stringify(o.label)} },`)
        .join("\n")
      return `  ${JSON.stringify(k)}: {\n    label: ${JSON.stringify(label)},\n    options: [\n${opts}\n    ],\n  },`
    })
    .join("\n")
  return `// AUTO-GENERATED by scripts/generate-dict-catalog.cjs —— 请勿手改
// 源头: ${SOURCE_SQL} 的 system_dict_type / system_dict_data
// 字典是**唯一真源**；元数据只声明 \`dictType\` 链接，不复制取值（§25）。

export type DictOption = { value: string; label: string }
export type DictEntry = { label: string; options: DictOption[] }

export const SYSTEM_DICT_CATALOG: Record<string, DictEntry> = {
${body}
}

export function dictEntry(type: string | undefined): DictEntry | undefined {
  if (!type) return undefined
  return SYSTEM_DICT_CATALOG[type]
}

export function dictValues(type: string | undefined): string[] | undefined {
  const entry = dictEntry(type)
  return entry ? entry.options.map((o) => o.value) : undefined
}

export function dictLabels(type: string | undefined): Record<string, string> | undefined {
  const entry = dictEntry(type)
  if (!entry) return undefined
  return Object.fromEntries(entry.options.map((o) => [o.value, o.label]))
}
`
}

function main() {
  const check = process.argv.includes("--check")
  let catalog
  try {
    catalog = readDict()
  } catch (error) {
    console.error(`[dict-catalog] ✗ ${error.message}`)
    process.exit(1)
  }

  const content = render(catalog)
  const abs = path.join(ROOT, OUT)
  const existing = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null
  const total = Object.values(catalog).reduce((n, e) => n + e.options.length, 0)

  if (check) {
    if (existing !== content) {
      console.error(`[dict-catalog] ✗ ${OUT} 与源头不一致 —— 请运行: node scripts/generate-dict-catalog.cjs`)
      process.exit(1)
    }
    console.log(`[dict-catalog] ✓ ${Object.keys(catalog).length} 个字典类型 / ${total} 条取值，与源头一致`)
    return
  }

  fs.writeFileSync(abs, content)
  console.log(`[dict-catalog] ✓ 已生成 ${OUT}（${Object.keys(catalog).length} 个类型 / ${total} 条取值）`)
}

main()
