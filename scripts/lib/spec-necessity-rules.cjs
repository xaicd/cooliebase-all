/**
 * 「这条需求是否需要走规格（spec）流程」的**规则表**。
 *
 * 为什么单独放一个文件：这是**产品决策**，不是实现细节。放在这里可以被审阅、被质疑、被修改，
 * 而不是藏在一个 `if` 里。每条规则都带 `reason`，分类器输出时会说明**命中了哪几条**，
 * 所以结论永远可溯源 —— 判错了，改的是这张表，不是去猜模型。
 *
 * 三条设计约束：
 * 1. **判不准时宁严勿宽**：命中任何 SPEC 规则即要求规格；两边都不命中 → 要求规格（fail-safe）。
 * 2. **不看模型心情**：纯文本规则匹配，同一条输入永远得到同一个结论。
 * 3. **不追求聪明**：宁可多要求一次规格（代价是几分钟），也不要漏掉一次该走的流程（代价是返工）。
 *
 * 修改本表后请跑 `npx vitest run test/unit/agent-route.test.ts` 确认判定没被意外改变。
 */

