const fs = require('fs')
const path = require('path')
const { execSync } = require('child_process')

const migDir = path.resolve(__dirname, '../prisma/migrations')

// 1. 删除旧迁移目录所有碎片
if (fs.existsSync(migDir)) {
  fs.rmSync(migDir, { recursive: true, force: true })
}

// 2. 创建单一初始迁移 V1 目录
const v1Dir = path.join(migDir, '20260824000000_init_v1')
fs.mkdirSync(v1Dir, { recursive: true })

// 3. 提取纯净 DDL
const ddl = execSync('pnpm exec prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script', { encoding: 'utf-8' })
fs.writeFileSync(path.join(v1Dir, 'migration.sql'), ddl, 'utf-8')

// 4. 写入 migration_lock.toml
fs.writeFileSync(path.join(migDir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n', 'utf-8')

console.log('[RESET-MIGRATIONS] Successfully reset Prisma migrations to clean V1.0.0 baseline!')
