import {
  type CodegenConfig,
  type CodegenMasterDetailChild,
  type CodegenOutput,
  type ConfiguredColumn,
  configuredColumns,
  formColumns,
  getBackendPath,
  isManagedColumn,
  toCamel,
  toKebab,
  toPascal,
} from "./common"

function childType(child: CodegenMasterDetailChild): string {
  const fields = child.fields.filter((field) => field.name !== child.foreignKeyField && !isManagedColumn(field) && field.readOnly !== true && field.uiComponent !== "HIDDEN")
  return `export interface ${toPascal(child.code)}ChildItem {\n${fields.map((field) => `  ${field.name}${field.nullable ? "?" : ""}: ${field.tsType}`).join("\n")}\n}`
}

export function generateTypes(config: CodegenConfig): CodegenOutput {
  const { className } = config
  const kebab = toKebab(className)
  const columns = configuredColumns(config)
  // **必须按列名去重**：元数据里可能出现同名列（实测 `iot-scene-rule` 重复 3 次、`mp-message` 重复 2 次），
  // 不去重会生成带 `Duplicate identifier` 的接口 —— 那种类型文件连解析都过不了，**但生成器自己是 exit=0**。
  const seenCols = new Set<string>()
  const uniqColumns = columns.filter((c) => {
    if (seenCols.has(c.name)) return false
    seenCols.add(c.name)
    return true
  })
  const writeCols = formColumns(config)
  const children = config.template === "MASTER_DETAIL" ? config.advanced?.model?.masterDetail?.children ?? [] : []
  const childTypes = children.map(childType).join("\n\n")
  const childFields = children.length ? `  children?: {\n${children.map((child) => `    ${child.code}: ${toPascal(child.code)}ChildItem[]`).join("\n")}\n  }\n` : ""

  const content = `// Auto-generated by Codegen Engine
${childTypes ? `${childTypes}\n\n` : ""}export interface ${className}DO {
${uniqColumns.map((c) => `  ${c.name}${c.nullable ? "?" : ""}: ${c.tsType}`).join("\n")}
}

export interface ${className}VO {
${uniqColumns.map((c) => `  ${c.name}${c.nullable ? "?" : ""}: ${c.tsType}`).join("\n")}
${childFields}}

export interface ${className}CreateDTO {
${writeCols.map((c) => `  ${c.name}${c.nullable ? "?" : ""}: ${c.tsType}`).join("\n")}
${childFields}}

export interface ${className}UpdateDTO extends Partial<${className}CreateDTO> {
  id: string
}

export interface ${className}PageQuery {
  page?: number
  pageSize?: number
${config.template === "TREE" ? `  tree?: "true" | "false"\n` : ""}${writeCols.filter((c) => c.queryType && c.queryType !== "NONE").map((c) => `  ${c.name}?: ${c.tsType}`).join("\n")}
}
${config.template === "TREE" ? `\nexport interface ${className}TreeVO extends ${className}VO {\n  children?: ${className}TreeVO[]\n}\n` : ""}`

  return { path: `${getBackendPath(config)}/types/${kebab}.types.ts`, content, type: "type" }
}
