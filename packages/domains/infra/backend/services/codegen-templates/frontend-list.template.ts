import {
  type CodegenConfig,
  type CodegenOutput,
  formColumns,
  getFrontendPath,
  queryColumns,
  toKebab,
  jsxText,
  resolveColumnEnum,
} from "./common"

export function generateListPage(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, businessName, submodule } = config
  const sub = submodule ? `/${submodule}` : ""
  const kebab = toKebab(className)
  const qCols = queryColumns(config)
  const displayCols = formColumns(config).slice(0, 6)

  const searchControls = qCols.map((c) => {
    const label = jsxText(c.comment) || c.name
    return `        <div className="flex items-center gap-1.5">
          <label htmlFor="${kebab}-search-${c.name}" className="text-xs text-slate-500 whitespace-nowrap">${label}:</label>
          <input
            type="text"
            id="${kebab}-search-${c.name}"
            data-testid="search-${c.name}"
            data-agent-target="${kebab}:field:${c.name}"
            data-agent-state={searchForm.${c.name} ? "filled" : "empty"}
            aria-label="${label}"
            value={searchForm.${c.name} ?? ""}
            onChange={(e) => setSearchForm((prev) => ({ ...prev, ${c.name}: e.target.value }))}
            placeholder="搜索${label}"
            className="w-36 px-2.5 py-1 text-xs border border-slate-200 rounded-lg focus:outline-none focus:ring-1 focus:ring-blue-500"
          />
        </div>`
  }).join("\n")

  const tableHeaders = displayCols.map((c) =>
    `                <th className="px-4 py-2.5 text-left text-[11px] font-semibold text-slate-500 uppercase tracking-wider">${jsxText(c.comment) || c.name}</th>`
  ).join("\n")

  const tableCells = displayCols.map((c) => {
    const resolvedEnum = resolveColumnEnum(c)
    if (!resolvedEnum) {
      return `                  <td className="px-4 py-2.5 text-xs text-slate-700 max-w-[200px] truncate" title={String(item.${c.name} ?? "-")}>{String(item.${c.name} ?? "-")}</td>`
    }
    const labels = JSON.stringify(resolvedEnum.labels)
    const primary = JSON.stringify(resolvedEnum.values[0])
    return `                  <td className="px-4 py-2.5 text-xs text-slate-700">
                    <EnumBadge value={item.${c.name}} labels={${labels}} primary={${primary}} />
                  </td>`
  }).join("\n")

  const advancedActions = (config.advanced as any)?.actions
  const isReadOnly = Array.isArray(advancedActions) && advancedActions.length === 0

  const content = `// Auto-generated by Codegen Engine\n"use client"

import React, { useState, useEffect, useCallback } from "react"
import { ${className}Api } from "../api/${kebab}.api"
import { ${className}Form } from "../components/${className}Form"
import { Pagination } from "@/modules/shared/frontend/components/pagination"
import type { ${className}VO, ${className}PageQuery } from "@/modules/${moduleName}${sub}/backend/types/${kebab}.types"

function EnumBadge({ value, labels, primary }: { value: unknown; labels: Record<string, string>; primary?: string }) {
  if (value === null || value === undefined || value === "") return <span className="text-slate-400">-</span>
  const key = String(value)
  const tone =
    key === primary
      ? "bg-emerald-50 text-emerald-700 border-emerald-200"
      : "bg-slate-100 text-slate-600 border-slate-200"
  return (
    <span className={"inline-flex items-center px-2 py-0.5 rounded-md border text-[11px] font-medium " + tone}>
      {labels[key] ?? key}
    </span>
  )
}

export function ${className}ListPage() {
  ${isReadOnly ? `// 当前发布版本未启用新增、编辑或删除动作，仅可查询。\n` : ""}  const [data, setData] = useState<${className}VO[]>([])
  const [total, setTotal] = useState(0)
  const [page, setPage] = useState(1)
  const [pageSize, setPageSize] = useState(20)
  const [loading, setLoading] = useState(false)
  const [searchForm, setSearchForm] = useState<Record<string, any>>({})
  const [formOpen, setFormOpen] = useState(false)
  const [editItem, setEditItem] = useState<${className}VO | null>(null)

  const fetchData = useCallback(async () => {
    setLoading(true)
    try {
      const res = await ${className}Api.page({ page, pageSize, ...searchForm })
      setData(res.items || [])
      setTotal(res.total || 0)
    } catch (err) {
      console.error("加载数据失败:", err)
    } finally {
      setLoading(false)
    }
  }, [page, pageSize, searchForm])

  useEffect(() => {
    fetchData()
  }, [fetchData])

  const handleSearch = (e: React.FormEvent) => {
    e.preventDefault()
    setPage(1)
    fetchData()
  }

  const handleReset = () => {
    setSearchForm({})
    setPage(1)
  }

  const handleAdd = () => {
    setEditItem(null)
    setFormOpen(true)
  }

  const handleEdit = (item: ${className}VO) => {
    setEditItem(item)
    setFormOpen(true)
  }

  const handleDelete = async (id: string) => {
    if (!window.confirm("确定要删除该记录吗？")) return
    try {
      await ${className}Api.delete(id)
      fetchData()
    } catch (err: any) {
      alert(err?.message || "删除失败")
    }
  }

  // Agent-Native: 根节点暴露就绪信号；弹窗打开时基底打 inert，让无障碍树只留弹窗一层
  const agentState = loading ? "loading" : formOpen ? "modal-open" : total === 0 ? "empty" : "ready"

  return (
    <div
      data-agent-scope="${kebab}"
      data-agent-state={agentState}
      data-agent-page-ready={String(!loading)}
      className="p-6 space-y-4"
    >
      {/* 弹窗打开时基底内容 inert —— Agent 不会误点到被遮挡的元素 */}
      <div inert={formOpen ? true : undefined} className="space-y-4">
      {/* 页面头部 */}
      <div className="flex items-center justify-between">
        <div>
          <h1 data-testid="${kebab}-title" className="text-xl font-bold tracking-tight text-slate-900">${businessName}管理</h1>
          <p className="text-xs text-slate-500 mt-0.5">${businessName}列表与配置管理</p>
        </div>
        <div className="flex items-center gap-2">
          <button
            onClick={fetchData}
            data-testid="${kebab}-refresh"
            data-agent-target="${kebab}:refresh"
            className="px-3 py-1.5 text-xs text-slate-600 bg-white border border-slate-300 rounded-lg hover:bg-slate-50 transition-colors"
          >
            刷新
          </button>
          <button
            onClick={handleAdd}
            data-testid="${kebab}-create"
            data-agent-target="${kebab}:create"
            className="px-3.5 py-1.5 text-xs text-white bg-blue-600 rounded-lg hover:bg-blue-700 transition-colors font-medium shadow-xs"
          >
            + 新增${businessName}
          </button>
        </div>
      </div>

      {/* 搜索工具栏 */}
      <form
        onSubmit={handleSearch}
        data-testid="${kebab}-search"
        data-agent-scope="${kebab}:search"
        aria-label="${businessName}搜索"
        className="p-3.5 bg-white rounded-xl border border-slate-200 shadow-xs flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-3">
${searchControls}
          <button type="submit" data-testid="${kebab}-search-submit" data-agent-target="${kebab}:search" className="px-3 py-1 text-xs text-white bg-slate-900 rounded-lg hover:bg-slate-800 transition-colors">查询</button>
          <button type="button" onClick={handleReset} data-testid="${kebab}-search-reset" data-agent-target="${kebab}:reset" className="px-3 py-1 text-xs text-slate-600 bg-slate-100 rounded-lg hover:bg-slate-200 transition-colors">重置</button>
        </div>
        <div className="text-xs text-slate-500">共 <span data-testid="${kebab}-total" className="font-semibold text-slate-700">{total}</span> 条记录</div>
      </form>

      {/* 数据表格 */}
      <div className="bg-white rounded-xl border border-slate-200 shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table data-testid="${kebab}-table" aria-label="${businessName}列表" className="min-w-full divide-y divide-slate-200">
            <thead className="bg-slate-50/80">
              <tr>
${tableHeaders}
                <th className="px-4 py-2.5 text-right text-[11px] font-semibold text-slate-500 uppercase tracking-wider min-w-[140px]">操作</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-200 bg-white">
              {loading ? (
                <tr>
                  <td colSpan={${displayCols.length + 1}} className="px-4 py-8 text-center text-xs text-slate-400">加载中...</td>
                </tr>
              ) : data.length === 0 ? (
                <tr>
                  <td colSpan={${displayCols.length + 1}} className="px-4 py-8 text-center text-xs text-slate-400">暂无数据</td>
                </tr>
              ) : (
                data.map((item) => (
                  <tr
                    key={item.id}
                    data-testid="${kebab}-row"
                    data-agent-target="${kebab}:row"
                    data-agent-state={editItem?.id === item.id ? "editing" : "idle"}
                    data-agent-id={item.id}
                    className="hover:bg-slate-50/60 transition-colors"
                  >
${tableCells}
                    <td className="px-4 py-2.5 text-xs text-right whitespace-nowrap space-x-2">
                      <button onClick={() => handleEdit(item)} data-testid="${kebab}-edit" data-agent-target="${kebab}:edit" data-agent-id={item.id} aria-label={"编辑 " + item.id} className="text-blue-600 hover:text-blue-800 font-medium">编辑</button>
                      <button onClick={() => handleDelete(item.id)} data-testid="${kebab}-delete" data-agent-target="${kebab}:delete" data-agent-id={item.id} aria-label={"删除 " + item.id} className="text-rose-600 hover:text-rose-800 font-medium">删除</button>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>

        {/* 分页组件 */}
        <div data-agent-target="${kebab}:pagination" className="p-3 border-t border-slate-200">
          <Pagination
            total={total}
            page={page}
            pageSize={pageSize}
            onPageChange={(p) => setPage(p)}
            onPageSizeChange={(ps) => setPageSize(ps)}
          />
        </div>
      </div>

      </div>

      {/* 弹窗表单 */}
      <${className}Form
        open={formOpen}
        initialData={editItem}
        onClose={() => setFormOpen(false)}
        onSuccess={fetchData}
      />
    </div>
  )
}
`
  return { path: `${getFrontendPath(config)}/pages/${kebab}-list.page.tsx`, content, type: "page" }
}
