import {
  type CodegenConfig,
  type CodegenOutput,
  type ConfiguredColumn,
  formColumns,
  getBackendPath,
  toCamel,
  toKebab,
} from "./common"

/** 该列在真实库上是否**必填**（NOT NULL，或业务上标了 required）。 */
function isRequiredColumn(column: ConfiguredColumn): boolean {
  return column.nullable === false || column.formValidation === "required" || column.validation?.required === true
}

/**
 * 按列类型生成一个**合法**的测试值。
 *
 * 为什么需要: 生成器原先只填第一列，其余必填列留空。内存回退**不校验约束**，
 * 所以测试在内存模式下能过；一配真实库就 `null value in column "..." violates
 * not-null constraint` —— 这类测试**只在内存模式下成立**，等于没测。
 */
/**
 * 生成一个**不超过列长度上限**的字符串字面量。
 *
 * 为什么需要: 生成器把所有字符串列都填成同一个长业务名，而真实列常有长度上限
 * （如 `status varchar(20)`）。内存回退不校验长度，测试就"通过"；
 * 一配真实库直接 `value too long for type character varying(20)`（实测 `ai_model`）。
 * 元数据没记 `maxLength` 时无法判断，只能按原值生成 —— 那是元数据的缺口，
 * 不是这里可以猜的（`scripts/fill-missing-columns.ts` 会从 information_schema 补录）。
 */
function stringLiteral(raw: string, maxLength?: number): string {
  if (typeof maxLength === "number" && maxLength > 0 && raw.length > maxLength) {
    return `"${raw.slice(0, maxLength)}"`
  }
  return `"${raw}"`
}

function sampleValue(column: ConfiguredColumn, businessName: string): string {
  // **按数据库类型判**，不要只看 tsType —— 元数据里存在 `tsType: "string"` 但
  // 物理列是 integer 的情况（导入器的启发式推断），只按 tsType 会生成字符串，
  // 连真实库时报 `invalid input syntax for type integer`（实测 20 例）。
  const dbType = (column.type ?? "").toLowerCase()
  if (["int", "integer", "bigint", "smallint", "decimal", "numeric", "float", "double"].includes(dbType)) {
    return dbType.startsWith("decimal") || dbType.startsWith("numeric") || dbType.startsWith("float") || dbType.startsWith("double") ? "1.5" : "1"
  }
  if (["boolean", "bool"].includes(dbType)) return "true"
  if (["timestamp", "timestamptz", "date", "datetime"].includes(dbType)) return "new Date().toISOString()"
  switch (column.tsType) {
    case "number":
      return column.type === "decimal" ? "1.5" : "1"
    case "boolean":
      return "true"
    case "string":
      if (column.type === "timestamp" || column.name.endsWith("_time") || column.name.endsWith("_at")) {
        return "new Date().toISOString()"
      }
      return stringLiteral(`测试${businessName}`, column.maxLength)
    default:
      return stringLiteral(`测试${businessName}`, column.maxLength)
  }
}

export function generateTest(config: CodegenConfig): CodegenOutput {
  const { className, businessName } = config
  const kebab = toKebab(className)
  const writeCols = formColumns(config)
  // 必填列要取**表里所有 NOT NULL 列**，不能只看 formColumns ——
  // 有些列不在表单里（如 model_key），但表要求非空，只填表单列就会
  // `null value in column "..." violates not-null constraint`（实测）。
    const requiredTableCols = (config.table.columns as ConfiguredColumn[]).filter(
      (column) => isRequiredColumn(column) && column.name !== "id" && column.name !== "tenant_id",
    )
    const payloadCols: ConfiguredColumn[] = [
      ...writeCols,
      ...requiredTableCols.filter((column) => !writeCols.some((existing) => existing.name === column.name)),
    ]
  const updateCol = writeCols[0] ?? { name: "name", tsType: "string", type: "varchar" }

  // 必填列必须全部填上 —— 否则连真实库就挂（内存模式掩盖了它）。
  const requiredCols = payloadCols.filter(isRequiredColumn)
  const createPayloadCols = requiredCols.length > 0 ? requiredCols : payloadCols.slice(0, 1)
  const createPayload = createPayloadCols.map((column) => `      ${column.name}: ${sampleValue(column, businessName)},`).join("\n")

  // 租户托管列（tenant_id）不在 formColumns 里 —— 它由**全局上下文**提供（AGENTS §4.8）。
  // 生成的测试原先不建立上下文，于是插入时 tenant_id 为 null，连真实库必然
  // `null value in column "tenant_id"`（内存回退同样掩盖了它）。
  const hasTenant = config.table.columns.some((column) => column.name === "tenant_id")
  const tenantImport = hasTenant ? `import { runWithTenantContext } from "@/modules/shared/backend/lib/biz-tenant"\n` : ""
  const body = `    const created = await ${className}Service.create({
${createPayload}
    } as any)
    expect(created).toBeDefined()
    expect(created.id).toBeDefined()

    const list = await ${className}Service.page({ page: 1, pageSize: 10 })
    expect(list.items.length).toBeGreaterThan(0)

    const fetched = await ${className}Service.get(created.id)
    expect(fetched).toBeDefined()
    expect(fetched?.id).toBe(created.id)

    const updated = await ${className}Service.update(created.id, {
      id: created.id,
        ${updateCol.name}: ${sampleValue(updateCol as ConfiguredColumn, `更新${businessName}`)},
    } as any)
    expect(updated).toBeDefined()

    const deleted = await ${className}Service.delete(created.id)
    expect(deleted).toBe(true)`

  const bodyWithContext = hasTenant
    ? `    await runWithTenantContext({ tenantId: "1" }, async () => {\n${body.replace(/^/gm, "  ")}\n    })`
    : body

  const content = `// Auto-generated by Codegen Engine (Service Unit Test)
import { describe, it, expect } from "vitest"
${tenantImport}import { ${className}Service } from "../${kebab}.service"

describe("${className}Service", () => {
  it("should create and query ${businessName}", async () => {
${bodyWithContext}
  })
})
`
  return { path: `${getBackendPath(config)}/services/__tests__/${kebab}.service.test.ts`, content, type: "test" }
}
