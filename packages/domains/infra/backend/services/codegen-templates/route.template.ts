import {
  type CodegenConfig,
  type CodegenOutput,
  toCamel,
  toConstant,
  toKebab,
} from "./common"

export function generateRoute(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, submodule } = config
  const sub = submodule ? `/${submodule}` : ""
  const kebab = toKebab(className)
  const camel = toCamel(className)
  const constName = toConstant(className)
  const entitySlug = kebab.startsWith(`${moduleName}-`) ? kebab.slice(moduleName.length + 1) : kebab
  const resolvedPermPrefix = config.permissionPrefix ?? `${moduleName}:${entitySlug}`
  const constPrefix = resolvedPermPrefix.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase()
  const isManagedTable = config.onlineRuntime?.storageKind === "MANAGED_TABLE"

  const viewPermExpr = isManagedTable ? "PERMISSIONS.INFRA_ONLINE_DEFINITION_QUERY" : `PERMISSIONS.${constPrefix}_VIEW`
  const createPermExpr = isManagedTable ? "PERMISSIONS.INFRA_ONLINE_DEFINITION_CREATE" : `PERMISSIONS.${constPrefix}_CREATE`
  const updatePermExpr = isManagedTable ? "PERMISSIONS.INFRA_ONLINE_DEFINITION_UPDATE" : `PERMISSIONS.${constPrefix}_UPDATE`
  const deletePermExpr = isManagedTable ? "PERMISSIONS.INFRA_ONLINE_DEFINITION_DELETE" : `PERMISSIONS.${constPrefix}_DELETE`

  const content = `// Auto-generated by Codegen Engine (API Route)
import { NextResponse } from "next/server"
import { withAdminRoute } from "@/modules/shared/backend/http/admin-route"
import { ${className}Service } from "@/modules/${moduleName}${sub}/backend/services/${kebab}.service"
import {
  ${camel}CreateSchema,
  ${camel}PageQuerySchema,
  ${camel}UpdateSchema,
} from "@/modules/${moduleName}${sub}/backend/validators/${kebab}.validator"
import { ${constName}_ACTION_SCHEMAS } from "@/modules/${moduleName}${sub}/contract/${kebab}.actions"
import { PERMISSIONS } from "@/modules/shared/backend/constants/permissions"
import { ApiError } from "@/modules/shared/backend/http/api-error"

// 权限码静态取键：若对应键未在 permissions.ts 登记，编译期即触发 TS2339 拦截（禁止动态拼接兜底）
const VIEW_PERM = ${viewPermExpr}
const CREATE_PERM = ${createPermExpr}
const UPDATE_PERM = ${updatePermExpr}
const DELETE_PERM = ${deletePermExpr}

function parseActionQuery(request: Request) {
  const { searchParams } = new URL(request.url)
  const raw: Record<string, unknown> = {}
  searchParams.forEach((v, k) => { raw[k] = v })
  return ${camel}PageQuerySchema.parse(raw)
}

function scope(auth: { userId?: string; tenantId?: string }) {
  if (${config.onlineRuntime?.storageKind === "MANAGED_TABLE" ? "!auth.tenantId" : "false"}) {
    throw new ApiError("FORBIDDEN", "Tenant scope is required")
  }
  return { actorId: auth.userId, tenantId: auth.tenantId }
}

export const GET = withAdminRoute(async (request, auth) => {
  const query = parseActionQuery(request)
  const s = scope(auth)
  const result = await ${className}Service.page(query, s.actorId, s.tenantId)
  return NextResponse.json({ success: true, data: result })
}, { permission: VIEW_PERM })

export const POST = withAdminRoute(async (request, auth) => {
  const body = await request.json()
  const data = ${camel}CreateSchema.parse(body)
  const result = await ${className}Service.create(data, auth.userId, auth.tenantId)
  return NextResponse.json({ success: true, data: result })
}, { permission: CREATE_PERM })

export const PUT = withAdminRoute(async (request, auth) => {
  const body = await request.json()
  const data = ${camel}UpdateSchema.parse(body)
  const result = await ${className}Service.update(data.id, data, auth.userId, auth.tenantId)
  return NextResponse.json({ success: true, data: result })
}, { permission: UPDATE_PERM })

export const DELETE = withAdminRoute(async (request, auth) => {
  const { searchParams } = new URL(request.url)
  const id = searchParams.get("id")
  if (!id) return NextResponse.json({ success: false, error: "id is required" }, { status: 400 })
  const result = await ${className}Service.delete(id, auth.userId, auth.tenantId)
  return NextResponse.json({ success: true, data: result })
}, { permission: DELETE_PERM })
`
  return { path: `src/app/api/v1/admin/${moduleName}${sub}/${kebab}/route.ts`, content, type: "route" }
}

export function generateActionRoutes(config: CodegenConfig): CodegenOutput[] {
  const { className, moduleName, submodule } = config
  const sub = submodule ? `/${submodule}` : ""
  const kebab = toKebab(className)
  const outputs: CodegenOutput[] = []

  const actions: Array<{ name: string; method: string; body: string; readsRequest?: boolean }> = [
    { name: "export", method: "POST", body: `  const result = await ${className}Service.page({ page: 1, pageSize: 1000 }, auth.userId, auth.tenantId)\n  return NextResponse.json({ success: true, data: result.items ?? result })` },
    { name: "import-template", method: "GET", body: `  return NextResponse.json({ success: true, data: { columns: [], sampleRows: [] } })` },
    { name: "import", method: "POST", body: `  return NextResponse.json({ success: true, data: { importedCount: 0 } })` },
  ]

  if (config.advanced?.stateMachine) {
    actions.push({
      name: "transition",
      method: "POST",
      readsRequest: true,
      body: `  const raw = await request.json()\n  const id = String(raw?.id ?? "")\n  const action = String(raw?.action ?? "")\n  const result = await ${className}Service.transition(id, action, auth.userId, auth.tenantId)\n  return NextResponse.json({ success: true, data: result })`,
    })
  }

  if (config.advanced?.convertActions?.length) {
    actions.push({
      name: "convert",
      method: "POST",
      readsRequest: true,
      body: `  const raw = await request.json()\n  const id = String(raw?.id ?? "")\n  const action = String(raw?.action ?? "")\n  const result = await ${className}Service.convert(id, action, raw?.overrides, auth.userId, auth.tenantId)\n  return NextResponse.json({ success: true, data: result })`,
    })
  }

  for (const act of actions) {
    const reqParam = act.readsRequest ? "request" : "_request"
    const content = `// Auto-generated by Codegen Engine (Action Route: ${act.name})
import { NextResponse } from "next/server"
import { withAdminRoute } from "@/modules/shared/backend/http/admin-route"
import { ${className}Service } from "@/modules/${moduleName}${sub}/backend/services/${kebab}.service"

export const ${act.method} = withAdminRoute(async (${reqParam}, auth) => {
${act.body}
})
`
    outputs.push({
      path: `src/app/api/v1/admin/${moduleName}${sub}/${kebab}/${act.name}/route.ts`,
      content,
      type: "route",
    })
  }

  return outputs
}
