import {
  type CodegenConfig,
  type CodegenOutput,
  getFrontendPath,
  toKebab,
} from "./common"

export function generateApiClient(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, submodule } = config
  const sub = submodule ? `/${submodule}` : ""
  const kebab = toKebab(className)

  const transitionMethod = config.advanced?.stateMachine
    ? `
  async transition(id: string, action: string) {
    return request.post<${className}VO>(\`\${BASE_URL}/transition\`, { id, action })
  },
`
    : ""

  const convertMethod = config.advanced?.convertActions?.length
    ? `
  async convert(id: string, action: string, overrides?: Record<string, unknown>) {
    return request.post<Record<string, unknown>>(\`\${BASE_URL}/convert\`, { id, action, overrides })
  },
`
    : ""

  const content = `// Auto-generated by Codegen Engine (Frontend API Client)
import { request } from "@/modules/shared/frontend/lib/request"
import type {
  ${className}CreateDTO,
  ${className}PageQuery,
  ${className}UpdateDTO,
  ${className}VO,
} from "@/modules/${moduleName}${sub}/backend/types/${kebab}.types"

const BASE_URL = "/api/v1/admin/${moduleName}${sub}/${kebab}"

export const ${className}Api = {
  async page(params?: ${className}PageQuery) {
    return request.get<{ items: ${className}VO[]; total: number }>(BASE_URL, { params })
  },

  async get(id: string) {
    return request.get<${className}VO>(\`\${BASE_URL}/\${id}\`)
  },

  async create(data: ${className}CreateDTO) {
    return request.post<${className}VO>(BASE_URL, data)
  },

  async update(data: ${className}UpdateDTO) {
    return request.put<${className}VO>(\`\${BASE_URL}/\${data.id}\`, data)
  },

  async delete(id: string) {
    return request.delete<void>(\`\${BASE_URL}/\${id}\`)
  },
${transitionMethod}${convertMethod}
  async export(params?: ${className}PageQuery) {
    return request.post<${className}VO[]>(\`\${BASE_URL}/export\`, params)
  },

  async getImportTemplate() {
    return request.get<{ columns: string[]; sampleRows: Record<string, unknown>[] }>(\`\${BASE_URL}/import-template\`)
  },

  async import(file: File) {
    const formData = new FormData()
    formData.append("file", file)
    return request.post<{ importedCount: number }>(\`\${BASE_URL}/import\`, formData)
  },
}
`
  return { path: `${getFrontendPath(config)}/api/${kebab}.api.ts`, content, type: "api" }
}
