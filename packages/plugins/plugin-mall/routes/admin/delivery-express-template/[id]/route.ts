import { NextResponse } from "next/server"
import { DeliveryExpressTemplateService } from "@/modules/mall/backend/services/delivery-express-template.service"
import { deliveryExpressTemplateCreateSchema, deliveryExpressTemplatePageQuerySchema, deliveryExpressTemplateUpdateSchema } from "@/modules/mall/backend/validators/delivery-express-template.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await DeliveryExpressTemplateService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await DeliveryExpressTemplateService.update(id, deliveryExpressTemplateUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await DeliveryExpressTemplateService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
