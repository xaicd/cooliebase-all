import { NextResponse } from "next/server"
import { ProductBrandService } from "@/modules/mall/backend/services/product-brand.service"
import { productBrandCreateSchema, productBrandPageQuerySchema, productBrandUpdateSchema } from "@/modules/mall/backend/validators/product-brand.validator"

export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url)
    const raw: Record<string, unknown> = {}
    searchParams.forEach((value, key) => { raw[key] = value })
    const input = productBrandPageQuerySchema.parse(raw)
    const data = await ProductBrandService.page(input)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "查询失败" }, { status: 400 })
  }
}

export async function POST(request: Request) {
  try {
    const body = await request.json()
    const data = await ProductBrandService.create(productBrandCreateSchema.parse(body))
    return NextResponse.json({ success: true, data }, { status: 201 })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "创建失败" }, { status: 400 })
  }
}
