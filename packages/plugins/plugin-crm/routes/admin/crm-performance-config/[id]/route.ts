import { NextResponse } from "next/server"
import { CrmPerformanceConfigService } from "@/modules/crm/backend/services/crm-performance-config.service"
import { crmPerformanceConfigCreateSchema, crmPerformanceConfigPageQuerySchema, crmPerformanceConfigUpdateSchema } from "@/modules/crm/backend/validators/crm-performance-config.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await CrmPerformanceConfigService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await CrmPerformanceConfigService.update(id, crmPerformanceConfigUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await CrmPerformanceConfigService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
