import { NextResponse } from "next/server"
import { CrmFollowUpRecordService } from "@/modules/crm/backend/services/crm-follow-up-record.service"
import { crmFollowUpRecordCreateSchema, crmFollowUpRecordPageQuerySchema, crmFollowUpRecordUpdateSchema } from "@/modules/crm/backend/validators/crm-follow-up-record.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await CrmFollowUpRecordService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await CrmFollowUpRecordService.update(id, crmFollowUpRecordUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await CrmFollowUpRecordService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
