import { NextResponse } from "next/server"
import { CrmBusinessService } from "@/modules/crm/backend/services/crm-business.service"
import { crmBusinessCreateSchema, crmBusinessPageQuerySchema, crmBusinessUpdateSchema } from "@/modules/crm/backend/validators/crm-business.validator"

export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url)
    const raw: Record<string, unknown> = {}
    searchParams.forEach((value, key) => { raw[key] = value })
    const input = crmBusinessPageQuerySchema.parse(raw)
    const data = await CrmBusinessService.page(input)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "查询失败" }, { status: 400 })
  }
}

export async function POST(request: Request) {
  try {
    const body = await request.json()
    const data = await CrmBusinessService.create(crmBusinessCreateSchema.parse(body))
    return NextResponse.json({ success: true, data }, { status: 201 })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "创建失败" }, { status: 400 })
  }
}
