import { NextResponse } from "next/server"
import { CrmCustomerPoolConfigService } from "@/modules/crm/backend/services/crm-customer-pool-config.service"
import { crmCustomerPoolConfigCreateSchema, crmCustomerPoolConfigPageQuerySchema, crmCustomerPoolConfigUpdateSchema } from "@/modules/crm/backend/validators/crm-customer-pool-config.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await CrmCustomerPoolConfigService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await CrmCustomerPoolConfigService.update(id, crmCustomerPoolConfigUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await CrmCustomerPoolConfigService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
