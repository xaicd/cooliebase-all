import { NextResponse } from "next/server"
import { MesProWorkRecordLogService } from "@/modules/mes/backend/services/mes-pro-work-record-log.service"
import { mesProWorkRecordLogCreateSchema, mesProWorkRecordLogPageQuerySchema, mesProWorkRecordLogUpdateSchema } from "@/modules/mes/backend/validators/mes-pro-work-record-log.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesProWorkRecordLogService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await MesProWorkRecordLogService.update(id, mesProWorkRecordLogUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesProWorkRecordLogService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
