import { NextResponse } from "next/server"
import { MesMdWorkstationMachineService } from "@/modules/mes/backend/services/mes-md-workstation-machine.service"
import { mesMdWorkstationMachineCreateSchema, mesMdWorkstationMachinePageQuerySchema, mesMdWorkstationMachineUpdateSchema } from "@/modules/mes/backend/validators/mes-md-workstation-machine.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesMdWorkstationMachineService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await MesMdWorkstationMachineService.update(id, mesMdWorkstationMachineUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesMdWorkstationMachineService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
