import { NextResponse } from "next/server"
import { MesWmItemReceiptLineService } from "@/modules/mes/backend/services/mes-wm-item-receipt-line.service"
import { mesWmItemReceiptLineCreateSchema, mesWmItemReceiptLinePageQuerySchema, mesWmItemReceiptLineUpdateSchema } from "@/modules/mes/backend/validators/mes-wm-item-receipt-line.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesWmItemReceiptLineService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await MesWmItemReceiptLineService.update(id, mesWmItemReceiptLineUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesWmItemReceiptLineService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
