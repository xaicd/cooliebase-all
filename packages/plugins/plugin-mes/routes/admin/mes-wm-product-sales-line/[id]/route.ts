import { NextResponse } from "next/server"
import { MesWmProductSalesLineService } from "@/modules/mes/backend/services/mes-wm-product-sales-line.service"
import { mesWmProductSalesLineCreateSchema, mesWmProductSalesLinePageQuerySchema, mesWmProductSalesLineUpdateSchema } from "@/modules/mes/backend/validators/mes-wm-product-sales-line.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesWmProductSalesLineService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await MesWmProductSalesLineService.update(id, mesWmProductSalesLineUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesWmProductSalesLineService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
