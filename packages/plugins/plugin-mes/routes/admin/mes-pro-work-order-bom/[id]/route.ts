import { NextResponse } from "next/server"
import { MesProWorkOrderBomService } from "@/modules/mes/backend/services/mes-pro-work-order-bom.service"
import { mesProWorkOrderBomCreateSchema, mesProWorkOrderBomPageQuerySchema, mesProWorkOrderBomUpdateSchema } from "@/modules/mes/backend/validators/mes-pro-work-order-bom.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesProWorkOrderBomService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await MesProWorkOrderBomService.update(id, mesProWorkOrderBomUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await MesProWorkOrderBomService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
