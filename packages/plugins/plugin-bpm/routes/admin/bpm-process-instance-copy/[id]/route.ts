import { NextResponse } from "next/server"
import { BpmProcessInstanceCopyService } from "@/modules/bpm/backend/services/bpm-process-instance-copy.service"
import { bpmProcessInstanceCopyCreateSchema, bpmProcessInstanceCopyPageQuerySchema, bpmProcessInstanceCopyUpdateSchema } from "@/modules/bpm/backend/validators/bpm-process-instance-copy.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await BpmProcessInstanceCopyService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await BpmProcessInstanceCopyService.update(id, bpmProcessInstanceCopyUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await BpmProcessInstanceCopyService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
