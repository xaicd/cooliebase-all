import { NextResponse } from "next/server"
import { ErpPurchaseReturnItemService } from "@/modules/erp/backend/services/erp-purchase-return-item.service"
import { erpPurchaseReturnItemCreateSchema, erpPurchaseReturnItemPageQuerySchema, erpPurchaseReturnItemUpdateSchema } from "@/modules/erp/backend/validators/erp-purchase-return-item.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await ErpPurchaseReturnItemService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await ErpPurchaseReturnItemService.update(id, erpPurchaseReturnItemUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await ErpPurchaseReturnItemService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
