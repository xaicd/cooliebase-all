import { NextResponse } from "next/server"
import { ErpFinanceReceiptService } from "@/modules/erp/backend/services/erp-finance-receipt.service"
import { erpFinanceReceiptCreateSchema, erpFinanceReceiptPageQuerySchema, erpFinanceReceiptUpdateSchema } from "@/modules/erp/backend/validators/erp-finance-receipt.validator"

type RouteContext = { params: Promise<{ id: string }> }

export async function GET(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await ErpFinanceReceiptService.get(id)
    if (!data) return NextResponse.json({ success: false, error: "不存在" }, { status: 404 })
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function PUT(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const body = await request.json()
    const data = await ErpFinanceReceiptService.update(id, erpFinanceReceiptUpdateSchema.parse({ ...body, id }))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}

export async function DELETE(request: Request, context: RouteContext) {
  try {
    const { id } = await context.params
    const data = await ErpFinanceReceiptService.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message }, { status: 400 })
  }
}
